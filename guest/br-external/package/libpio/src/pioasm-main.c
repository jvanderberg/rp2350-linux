int main(int argc, char **argv)
{
    const char *in = NULL, *out = NULL;
    int version = -1;
    char err[256];
    FILE *fi = stdin, *fo = stdout;

    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "-o") && i + 1 < argc) {
            if (strcmp(argv[++i], "c-sdk")) {
                fprintf(stderr, "pioasm: only -o c-sdk\n");
                return 1;
            }
        } else if (!strcmp(argv[i], "-v") && i + 1 < argc) {
            version = atoi(argv[++i]);
        } else if (!strcmp(argv[i], "-h") || !strcmp(argv[i], "--help")) {
            fprintf(stderr, "usage: pioasm [-o c-sdk] [-v VERSION] input.pio [output.h]\n");
            return 0;
        } else if (!in) {
            in = argv[i];
        } else if (!out) {
            out = argv[i];
        } else {
            fprintf(stderr, "usage: pioasm [-o c-sdk] [-v VERSION] input.pio [output.h]\n");
            return 1;
        }
    }
    if (in && strcmp(in, "-") && !(fi = fopen(in, "r"))) {
        perror(in);
        return 1;
    }
    char *src = slurp(fi);
    if (!src) {
        fprintf(stderr, "pioasm: out of memory\n");
        return 1;
    }
    pioasm_file_t *f = pioasm_parse(src, err, sizeof(err));
    if (!f) {
        fprintf(stderr, "%s: %s\n", in ? in : "<stdin>", err);
        return 1;
    }
    if (out && !(fo = fopen(out, "w"))) {
        perror(out);
        return 1;
    }
    emit(fo, f, version);
    if (fo != stdout && fclose(fo)) {
        perror(out);
        return 1;
    }
    pioasm_free(f);
    free(src);
    return 0;
}
