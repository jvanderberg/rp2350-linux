/* pioasm: a .pio file to a C header for libpio, as the pico-sdk's pioasm
 * does it (its c-sdk output, with each program's `% c-sdk { %}` text).
 *
 *   pioasm [-o c-sdk] [-v VERSION] input.pio [output.h]
 *
 * "-" (or no input) reads standard input; no output writes standard
 * output. */
#define _GNU_SOURCE
#include "pio.h"
#include "pioasm.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static char *slurp(FILE *f)
{
    size_t cap = 4096, n = 0, r;
    char *b = malloc(cap);

    while (b && (r = fread(b + n, 1, cap - n - 1, f)) > 0) {
        n += r;
        if (n + 1 == cap) {
            char *nb = realloc(b, cap *= 2);
            if (!nb) {
                free(b);
                return NULL;
            }
            b = nb;
        }
    }
    if (b)
        b[n] = 0;
    return b;
}

/* The header emit() writes is the pico-sdk pioasm's c-sdk output
 * (tools/pioasm/c_sdk_output.cpp, https://github.com/raspberrypi/pico-sdk):
 * the banner, the instruction listing, the pio_program and the
 * _get_default_config function in its words and layout. The code is
 * libpio's, but the output text is the SDK's, so this carries its notice.
 * The license text: LICENSE-BSD-3-Clause.
 *
 * SPDX-SnippetBegin
 * SPDX-SnippetCopyrightText: Copyright (c) 2020 Raspberry Pi (Trading) Ltd.
 * SPDX-License-Identifier: BSD-3-Clause
 */
static void emit(FILE *o, const pioasm_file_t *f, int force_version)
{
    fprintf(o, "// -------------------------------------------------- //\n"
               "// This file is autogenerated by pioasm; do not edit! //\n"
               "// -------------------------------------------------- //\n\n"
               "#pragma once\n\n#include <pio.h>\n\n");
    for (int k = 0; k < f->count; k++) {
        const pio_asm_program_t *p = &f->programs[k];
        const char *n = p->name;
        int bar = (int)strlen(n) + 6;
        int ver = force_version >= 0 && force_version > p->program.pio_version ? force_version : p->program.pio_version;

        fprintf(o, "// %.*s //\n// %s //\n// %.*s //\n\n", bar - 6, "------------------------------------------------", n,
                bar - 6, "------------------------------------------------");
        fprintf(o, "#define %s_wrap_target %u\n#define %s_wrap %u\n#define %s_pio_version %d\n\n", n, p->wrap_target, n,
                p->wrap, n, ver);
        for (int i = 0; i < p->ndefines; i++)
            fprintf(o, "#define %s_%s %d\n", n, p->defines[i].name, p->defines[i].value);
        if (p->ndefines)
            fprintf(o, "\n");
        fprintf(o, "static const uint16_t %s_program_instructions[] = {\n", n);
        for (int i = 0; i < p->program.length; i++) {
            if (i == p->wrap_target)
                fprintf(o, "            //     .wrap_target\n");
            fprintf(o, "    0x%04x, // %2d: %s\n", p->instructions[i], i, f->listing[k][i][0] ? f->listing[k][i] : ".word");
            if (i == p->wrap)
                fprintf(o, "            //     .wrap\n");
        }
        fprintf(o, "};\n\n");
        fprintf(o, "static const struct pio_program %s_program = {\n"
                   "    .instructions = %s_program_instructions,\n"
                   "    .length = %u,\n"
                   "    .origin = %d,\n"
                   "    .pio_version = %d,\n"
                   "};\n\n",
                n, n, p->program.length, p->program.origin, ver);
        fprintf(o, "static inline pio_sm_config %s_program_get_default_config(uint offset) {\n"
                   "    pio_sm_config c = pio_get_default_sm_config();\n"
                   "    sm_config_set_wrap(&c, offset + %s_wrap_target, offset + %s_wrap);\n",
                n, n, n);
        if (p->sideset_bits || p->sideset_opt)
            fprintf(o, "    sm_config_set_sideset(&c, %d, %s, %s);\n", p->sideset_bits + p->sideset_opt,
                    p->sideset_opt ? "true" : "false", p->sideset_pindirs ? "true" : "false");
        if (p->has & 1)
            fprintf(o, "    sm_config_set_in_pin_count(&c, %d);\n    sm_config_set_in_shift(&c, %s, %s, %d);\n",
                    p->in_count ? p->in_count : 32, p->in_right ? "true" : "false", p->in_auto ? "true" : "false",
                    p->in_threshold ? p->in_threshold : 32);
        if (p->has & 2)
            fprintf(o, "    sm_config_set_out_pin_count(&c, %d);\n    sm_config_set_out_shift(&c, %s, %s, %d);\n",
                    p->out_count, p->out_right ? "true" : "false", p->out_auto ? "true" : "false",
                    p->out_threshold ? p->out_threshold : 32);
        if (p->has & 4)
            fprintf(o, "    sm_config_set_set_pin_count(&c, %d);\n", p->set_count);
        if (p->has & 8) {
            static const char *j[] = { "NONE", "TX", "RX", "", "TXGET", "", "", "", "TXPUT", "", "", "", "PUTGET" };
            fprintf(o, "    sm_config_set_fifo_join(&c, PIO_FIFO_JOIN_%s);\n", j[p->fifo]);
        }
        if (p->has & 16) {
            static const char *t[] = { "STATUS_TX_LESSTHAN", "STATUS_RX_LESSTHAN", "STATUS_IRQ_SET" };
            fprintf(o, "    sm_config_set_mov_status(&c, %s, %d);\n", t[p->mov_status_type], p->mov_status_n);
        }
        if (p->has & 32) {
            /* a float literal: 2 must be 2.0f, not 2f */
            char v[32];
            snprintf(v, sizeof(v), "%.9g", (double)p->clock_div);
            fprintf(o, "    sm_config_set_clkdiv(&c, %s%sf);\n", v, strpbrk(v, ".e") ? "" : ".0");
        }
        fprintf(o, "    return c;\n}\n\n");
        if (f->sdk_len[k])
            fwrite(f->sdk_text + f->sdk_start[k], 1, f->sdk_len[k], o), fprintf(o, "\n");
    }
}
